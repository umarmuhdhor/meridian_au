/**
 * One-shot local secret setup for a self-hosted (non-Docker) Meridian.
 *
 * Prompts for the 6-digit dashboard PIN (hidden — never echoed, never logged),
 * derives its scrypt hash, generates the daemon<->web bridge token and the
 * session-cookie secret, then upserts them into BOTH env files the two
 * processes actually read:
 *
 *   .env                     → daemon (dotenv, see src/entrypoints/load-env.ts)
 *   dashboard/web/.env.local → Next.js (loaded by `next start`)
 *
 * Existing DASHBOARD_TOKEN / MERIDIAN_SESSION_SECRET are reused so re-running
 * this only rotates the PIN. Pass --rotate to regenerate everything.
 *
 *   node scripts/setup-local-secrets.mjs
 *   node scripts/setup-local-secrets.mjs --rotate
 */
import { randomBytes, scryptSync } from "node:crypto";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENV_DAEMON = path.join(REPO_ROOT, ".env");
const ENV_WEB = path.join(REPO_ROOT, "dashboard", "web", ".env.local");
const ROTATE = process.argv.includes("--rotate");

/** Read a line from the tty without echoing it. */
function promptHidden(question) {
  return new Promise((resolve, reject) => {
    const { stdin, stdout } = process;
    if (!stdin.isTTY) {
      reject(new Error("no tty — run this in an interactive terminal"));
      return;
    }
    stdout.write(question);
    stdin.setRawMode(true);
    stdin.resume();
    stdin.setEncoding("utf8");
    let buf = "";
    const onData = (ch) => {
      switch (ch) {
        case "\n":
        case "\r":
        case "":
          stdin.setRawMode(false);
          stdin.pause();
          stdin.removeListener("data", onData);
          stdout.write("\n");
          resolve(buf);
          return;
        case "": // Ctrl-C
          stdin.setRawMode(false);
          stdout.write("\n");
          process.exit(130);
          return;
        case "": // backspace
        case "\b":
          buf = buf.slice(0, -1);
          return;
        default:
          buf += ch;
      }
    };
    stdin.on("data", onData);
  });
}

/** Parse KEY=VALUE lines; comments and blanks are ignored. */
function readEnv(file) {
  if (!existsSync(file)) return {};
  const out = {};
  for (const line of readFileSync(file, "utf8").split(/\r?\n/)) {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=(.*)$/.exec(line);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

/**
 * Rewrite KEY=... in place when present, append otherwise. Preserves comments
 * and ordering so the hand-written parts of .env survive.
 */
function upsertEnv(file, updates) {
  const lines = existsSync(file) ? readFileSync(file, "utf8").split(/\r?\n/) : [];
  const pending = new Map(Object.entries(updates));
  const next = lines.map((line) => {
    const m = /^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=/.exec(line);
    if (!m || !pending.has(m[1])) return line;
    const key = m[1];
    const value = pending.get(key);
    pending.delete(key);
    return `${key}=${value}`;
  });
  if (pending.size > 0) {
    if (next.length > 0 && next[next.length - 1].trim() !== "") next.push("");
    next.push("# --- generated by scripts/setup-local-secrets.mjs ---");
    for (const [key, value] of pending) next.push(`${key}=${value}`);
  }
  writeFileSync(file, next.join("\n").replace(/\n*$/, "\n"), { mode: 0o600 });
}

const pin = (await promptHidden("6-digit dashboard PIN: ")).trim();
if (!/^\d{6}$/.test(pin)) {
  console.error("PIN must be exactly 6 digits. Nothing written.");
  process.exit(1);
}
const confirm = (await promptHidden("Repeat PIN:            ")).trim();
if (confirm !== pin) {
  console.error("PINs do not match. Nothing written.");
  process.exit(1);
}

const existing = readEnv(ENV_DAEMON);
const bridgeToken = (!ROTATE && existing.DASHBOARD_TOKEN) || randomBytes(32).toString("hex");
const sessionSecret =
  (!ROTATE && existing.MERIDIAN_SESSION_SECRET) || randomBytes(32).toString("hex");

const salt = randomBytes(16).toString("hex");
const pinHash = `${salt}:${scryptSync(pin, salt, 64).toString("hex")}`;

upsertEnv(ENV_DAEMON, {
  DASHBOARD_TOKEN: bridgeToken,
  MERIDIAN_SESSION_SECRET: sessionSecret,
  MERIDIAN_DASHBOARD_PIN_HASH: pinHash,
});
upsertEnv(ENV_WEB, {
  BRIDGE_URL: "http://127.0.0.1:8787",
  BRIDGE_TOKEN: bridgeToken,
  MERIDIAN_ROOT: path.join(REPO_ROOT, "data").replace(/\\/g, "/"),
  MERIDIAN_SESSION_SECRET: sessionSecret,
  MERIDIAN_DASHBOARD_PIN_HASH: pinHash,
});

console.log(`wrote ${ENV_DAEMON}`);
console.log(`wrote ${ENV_WEB}`);
console.log(ROTATE ? "rotated: bridge token + session secret + PIN" : "PIN set (token/secret preserved)");
console.log("restart both processes:  pm2 restart all");
